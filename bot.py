@router.message(SuggestState.waiting_for_text)
async def process_suggestion(message: Message, state: FSMContext, bot: Bot):
    user_text = message.text
    user = message.from_user
    user_info = f"@{user.username}" if user.username else f"{user.first_name} (ID: {user.id})"
    
    # Зберігаємо в базу або одразу шлемо адміну
    conn = sqlite3.connect("umanelektro.db")
    cursor = conn.cursor()
    cursor.execute("INSERT INTO suggestions (user_id, user_name, text) VALUES (?, ?, ?)", 
                   (user.id, user_info, user_text))
    sug_id = cursor.lastrowid
    conn.commit()
    conn.close()
    
    # Кнопки для адміна
    kb = InlineKeyboardMarkup(inline_keyboard=[
        [
            InlineKeyboardButton(text="✅ Схвалити", callback_data=f"accept_{sug_id}"),
            InlineKeyboardButton(text="❌ Відхилити", callback_data=f"reject_{sug_id}")
        ]
    ])
    
    # Відправляємо адміну
    await bot.send_message(
        ADMIN_ID, 
        f"📩 **Нова пропозиція від {user_info}:**\n\n{user_text}",
        reply_markup=kb
    )
    
    await message.answer("Дякую! Твоя пропозиція надіслана на модерацію адміністратору.", reply_markup=get_main_keyboard())
    await state.clear()


@router.message()
async def search_handler(message: Message):
    query = message.text.strip()
    if not query:
        return

    conn = sqlite3.connect("umanelektro.db")
    cursor = conn.cursor()
    
    # Шукаємо в вулицях
    cursor.execute("SELECT name, queue FROM streets WHERE name LIKE ?", (f"%{query}%",))
    streets_found = cursor.fetchall()
    
    # Шукаємо в підприємствах
    cursor.execute("SELECT name, queue FROM enterprises WHERE name LIKE ?", (f"%{query}%",))
    enterprises_found = cursor.fetchall()
    
    conn.close()
    
    response = ""
    if streets_found:
        response += "📍 **Знайдені вулиці:**\n"
        for name, queue in streets_found[:10]: # Обмежимо до 10 результатів
            response += f"• {name} — <b>{queue}</b>\n"
        response += "\n"
        
    if enterprises_found:
        response += "🏢 **Знайдені підприємства:**\n"
        for name, queue in enterprises_found[:10]:
            response += f"• {name} — <b>{queue}</b>\n"
            
    if not streets_found and not enterprises_found:
        response = "Нічого не знайдено за твоїм запитом. Спробуй ввести іншу назву або скористайся кнопкою «✍️ Запропонувати зміни»."
        
    await message.answer(response, parse_mode="HTML")

